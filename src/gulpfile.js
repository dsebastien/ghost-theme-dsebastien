const {series, watch, src, dest, parallel} = require('gulp');
const pump = require('pump');

// gulp plugins and utils
const livereload = require('gulp-livereload');
const zip = require('gulp-zip').default;
const concat = require('gulp-concat');
const uglify = require('gulp-uglify');
const beeper = require('beeper');
const fs = require('fs');

function serve(done) {
    livereload.listen();
    done();
}

const handleError = (done) => {
    return function (err) {
        if (err) {
            beeper();
        }
        return done(err);
    };
};

function hbs(done) {
    pump([
        src(['*.hbs', 'partials/**/*.hbs']),
        livereload()
    ], handleError(done));
}

function js(done) {
    pump([
        src([
            // pull in lib files first so our own code can depend on it
            'assets/js/lib/*.js',
            'assets/js/*.js'
        ], {sourcemaps: true}),
        concat('source.js'),
        uglify(),
        dest('assets/built/', {sourcemaps: '.'}),
        livereload()
    ], handleError(done));
}

// Ghost themes cannot read src/data/pillars.json at render time, so the build
// turns it into a partial: partials/generated/pillar-feeds.hbs (the pillar feed
// list of the /feeds/ page, see feeds.hbs). Adding a pillar to pillars.json is
// enough: the next build regenerates the list. The output is committed so the
// theme also works without a build (gscan, docker serve).
function pillarFeeds(done) {
    const esc = (s) => String(s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
    const data = JSON.parse(fs.readFileSync('data/pillars.json', 'utf8'));
    const items = data.priorityOrder.map((slug) => {
        const p = data.pillars[slug];
        if (!p) throw new Error(`pillars.json: priorityOrder lists unknown pillar "${slug}"`);
        return [
            '    <li class="border-b border-gray-200 py-8">',
            '        <article>',
            `            <h3 class="text-2xl font-semibold !mb-2"><a href="/pillars/${slug}/">${esc(p.name)} ${p.emoji}</a></h3>`,
            `            <p class="text-gray-600">${esc(p.tagline)}</p>`,
            `            <p class="!mt-4"><a class="top-link" href="{{@site.url}}/pillars/${slug}/rss/"><code>{{@site.url}}/pillars/${slug}/rss/</code></a></p>`,
            '        </article>',
            '    </li>',
        ].join('\n');
    });
    const out = [
        '{{!-- GENERATED by gulpfile.js (pillarFeeds) from src/data/pillars.json. Do not edit: change pillars.json and run the build. --}}',
        '<ul class="!mx-0 space-y-8 !list-none">',
        ...items,
        '</ul>',
        '',
    ].join('\n');
    fs.mkdirSync('partials/generated', {recursive: true});
    const file = 'partials/generated/pillar-feeds.hbs';
    if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== out) fs.writeFileSync(file, out);
    done();
}

function zipper(done) {
    const filename = require('./package.json').name + '.zip';

    // Zip everything in the src directory except a few files
    pump([
        src([
            '**',
            '!node_modules', '!node_modules/**',
            '!dist', '!dist/**',
            '!bun.lock',
            '!gulpfile.js'
        ], {encoding: false}),
        zip(filename),
        dest('../dist/')
    ], handleError(done));
}

const jsWatcher = () => watch('assets/js/**', js);
const hbsWatcher = () => watch(['*.hbs', 'partials/**/*.hbs'], hbs);
const pillarsWatcher = () => watch('data/pillars.json', pillarFeeds);
const watcher = parallel(jsWatcher, hbsWatcher, pillarsWatcher);
const build = series(pillarFeeds, js);

exports.build = build;
exports.zip = series(build, zipper);
exports.default = series(build, serve, watcher);
